import type { Locator, Page } from "@playwright/test";
import * as YAML from "yaml";

import { test, expect } from "../fixtures/topoviewer";

const SIMPLE_FILE = "simple.clab.yml";
const SEL_LAB_SETTINGS_BTN = '[data-testid="navbar-lab-settings"]';
const SEL_LAB_SETTINGS_MODAL = '[data-testid="lab-settings-modal"]';
const SEL_TAB_CERTIFICATES = '[data-testid="lab-settings-tab-certificates"]';
const SEL_SAVE_BTN = '[data-testid="lab-settings-save-btn"]';

const WITH_CA = `name: simple

settings:
  # lab CA
  certificate-authority:
    key-size: 4096
    validity-duration: 1000h

topology:
  nodes:
    srl1:
      kind: nokia_srlinux
    srl2:
      kind: nokia_srlinux

  links:
    - endpoints: [ "srl1:e1-1", "srl2:e1-1" ]
`;

async function openCertificatesTab(page: Page): Promise<Locator> {
  await page.locator(SEL_LAB_SETTINGS_BTN).click();
  const modal = page.locator(SEL_LAB_SETTINGS_MODAL);
  await expect(modal).toBeVisible();
  await modal.locator(SEL_TAB_CERTIFICATES).click();
  await expect(modal.getByRole("combobox", { name: "Certificate Authority" })).toBeVisible();
  return modal;
}

test.describe("Lab settings: certificate authority", () => {
  test.beforeEach(async ({ topoViewerPage }) => {
    await topoViewerPage.resetFiles();
    await topoViewerPage.gotoFile(SIMPLE_FILE);
    await topoViewerPage.waitForCanvasReady();
    await topoViewerPage.setEditMode();
    await topoViewerPage.unlock();
  });

  test("sets the size and lifetime of the generated CA", async ({ page, topoViewerPage }) => {
    const modal = await openCertificatesTab(page);
    await expect(modal.getByRole("combobox", { name: "Certificate Authority" })).toContainText(
      "Generated by containerlab"
    );
    await modal.getByRole("textbox", { name: "Key Size" }).fill("4096");
    await modal.getByRole("textbox", { name: "Validity" }).fill("87600h");
    await modal.locator(SEL_SAVE_BTN).click();
    await expect(modal).toBeHidden();

    await expect
      .poll(async () => YAML.parse(await topoViewerPage.getYamlFromFile(SIMPLE_FILE)).settings)
      .toEqual({ "certificate-authority": { "key-size": 4096, "validity-duration": "87600h" } });
  });

  test("an existing CA needs both files and replaces the generator settings", async ({
    page,
    topoViewerPage
  }) => {
    await topoViewerPage.writeYamlFile(SIMPLE_FILE, WITH_CA);
    await topoViewerPage.waitForCanvasReady();
    const modal = await openCertificatesTab(page);
    await expect(modal.getByRole("textbox", { name: "Key Size" })).toHaveValue("4096");

    await modal.getByRole("combobox", { name: "Certificate Authority" }).click();
    await page.getByRole("option", { name: "Existing CA files" }).click();
    await modal.getByRole("textbox", { name: "CA Certificate" }).fill("ca/root.pem");
    await expect(modal.getByText("Required with an existing CA")).toBeVisible();

    // Apply from another tab returns to the certificates and writes nothing.
    await modal.getByTestId("lab-settings-tab-basic").click();
    await modal.locator(SEL_SAVE_BTN).click();
    await expect(modal.locator(SEL_TAB_CERTIFICATES)).toHaveAttribute("aria-current", "page");
    expect(await topoViewerPage.getYamlFromFile(SIMPLE_FILE)).toBe(WITH_CA);

    await modal.getByRole("textbox", { name: "CA Key" }).fill("ca/root.key");
    await modal.locator(SEL_SAVE_BTN).click();
    await expect(modal).toBeHidden();
    await expect
      .poll(() => topoViewerPage.getYamlFromFile(SIMPLE_FILE))
      .toBe(
        WITH_CA.replace(
          "    key-size: 4096\n    validity-duration: 1000h\n",
          "    cert: ca/root.pem\n    key: ca/root.key\n"
        )
      );
  });

  test("applying without changes leaves the file untouched", async ({ page, topoViewerPage }) => {
    await topoViewerPage.writeYamlFile(SIMPLE_FILE, WITH_CA);
    await topoViewerPage.waitForCanvasReady();
    const modal = await openCertificatesTab(page);
    await modal.locator(SEL_SAVE_BTN).click();
    await expect(modal).toBeHidden();
    expect(await topoViewerPage.getYamlFromFile(SIMPLE_FILE)).toBe(WITH_CA);
  });
});
