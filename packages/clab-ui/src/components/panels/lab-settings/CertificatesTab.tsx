// Certificate authority settings tab (settings.certificate-authority).
import React from "react";
import MenuItem from "@mui/material/MenuItem";
import TextField from "@mui/material/TextField";

import Box from "@mui/material/Box";

import { SettingsField } from "../../../settings/SettingsField";
import { useRuntimeLimit } from "../../../stores/labHostStore";
import { RuntimeLimited } from "../../ui/form";
import type { CertificateAuthorityIssues } from "../../../hooks/editor/labSettingsForm";

import type { CaMode, CertificateAuthorityState } from "./types";

interface CertificatesTabProps {
  ca: CertificateAuthorityState;
  setCa: (patch: Partial<CertificateAuthorityState>) => void;
  issues: CertificateAuthorityIssues;
  isViewMode: boolean;
}

interface CaTextFieldProps {
  id: string;
  title: string;
  description: string;
  placeholder: string;
  value: string;
  onChange: (value: string) => void;
  issue?: string;
  isViewMode: boolean;
}

const CaTextField: React.FC<CaTextFieldProps> = ({
  id,
  title,
  description,
  placeholder,
  value,
  onChange,
  issue,
  isViewMode
}) => (
  <SettingsField title={title} description={description}>
    <TextField
      slotProps={{ htmlInput: { "aria-label": title } }}
      id={id}
      size="small"
      placeholder={placeholder}
      value={value}
      onChange={(event) => onChange(event.target.value)}
      disabled={isViewMode}
      error={issue !== undefined}
      helperText={issue}
    />
  </SettingsField>
);

export const CertificatesTab: React.FC<CertificatesTabProps> = ({
  ca,
  setCa,
  issues,
  isViewMode
}) => {
  // c9s refuses the settings block; node certificates still come from clabernetes' CA.
  const caLimit = useRuntimeLimit("certificateAuthority");
  const isSet =
    ca.mode === "external" || [ca.cert, ca.key, ca.keySize, ca.validityDuration].some((value) => value !== "");
  const fields = (
    <>
      <SettingsField
        title="Certificate Authority"
        description="Signs the TLS certificates of nodes that get one, such as SR Linux. Containerlab generates a CA in the lab directory unless you provide one."
      >
        <TextField
          slotProps={{ select: { inputProps: { "aria-label": "Certificate Authority" } } }}
          id="lab-ca-mode"
          select
          size="small"
          value={ca.mode}
          onChange={(event) => setCa({ mode: event.target.value as CaMode })}
          disabled={isViewMode}
        >
          <MenuItem value="generated">Generated by containerlab (default)</MenuItem>
          <MenuItem value="external">Existing CA files</MenuItem>
        </TextField>
      </SettingsField>
      {ca.mode === "external" ? (
        <>
          <CaTextField
            id="lab-ca-cert"
            title="CA Certificate"
            description="Path to the CA certificate, absolute or relative to the topology file."
            placeholder="e.g., ca/root.pem"
            value={ca.cert}
            onChange={(cert) => setCa({ cert })}
            issue={issues.cert}
            isViewMode={isViewMode}
          />
          <CaTextField
            id="lab-ca-key"
            title="CA Key"
            description="Path to the CA private key, absolute or relative to the topology file."
            placeholder="e.g., ca/root.key"
            value={ca.key}
            onChange={(key) => setCa({ key })}
            issue={issues.key}
            isViewMode={isViewMode}
          />
        </>
      ) : (
        <>
          <CaTextField
            id="lab-ca-key-size"
            title="Key Size"
            description="Size of the generated CA key in bits."
            placeholder="2048"
            value={ca.keySize}
            onChange={(keySize) => setCa({ keySize })}
            issue={issues.keySize}
            isViewMode={isViewMode}
          />
          <CaTextField
            id="lab-ca-validity"
            title="Validity"
            description="How long the generated CA certificate is valid, for example 8760h for one year. Hours are the largest unit."
            placeholder="8760h"
            value={ca.validityDuration}
            onChange={(validityDuration) => setCa({ validityDuration })}
            issue={issues.validityDuration}
            isViewMode={isViewMode}
          />
        </>
      )}
    </>
  );
  if (!caLimit) return fields;
  return (
    <RuntimeLimited limit={caLimit} keepEditable={isSet} notePlacement="top">
      <Box sx={{ display: "grid", rowGap: 2, mt: 1 }}>{fields}</Box>
    </RuntimeLimited>
  );
};
